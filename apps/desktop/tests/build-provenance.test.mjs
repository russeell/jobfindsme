import test from 'node:test';
import assert from 'node:assert/strict';
import {mkdtempSync,mkdirSync,writeFileSync,rmSync} from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import {sourceDigest,assertProvenance} from '../scripts/build-provenance.mjs';

test('cached inputs detect source changes and ignore generated bytecode',()=>{
 const root=mkdtempSync(path.join(os.tmpdir(),'jfm-build-'));
 try{
  for(const dir of ['scripts','src'])mkdirSync(path.join(root,dir));
  writeFileSync(path.join(root,'scripts/desktop-build-inputs.json'),JSON.stringify({python:{directories:['src'],extensions:['.py'],files:[]}}));
  writeFileSync(path.join(root,'src/api.py'),'print("fixture")\n');
  const original=sourceDigest(root,'python');
  writeFileSync(path.join(root,'src/api.pyc'),'generated cache');assert.equal(sourceDigest(root,'python'),original);
  writeFileSync(path.join(root,'src/api.py'),'print("updated")\n');assert.notEqual(sourceDigest(root,'python'),original);
  for(const record of [undefined,{sourceCommit:'old',sourceDigest:original,dependencyLock:'lock'},{sourceCommit:'current',sourceDigest:original,dependencyLock:'other'}])assert.throws(()=>assertProvenance(record,{sourceCommit:'current',sourceDigest:original,dependencyLock:'lock'}),/rebuild/);
 }finally{rmSync(root,{recursive:true,force:true});}
});
